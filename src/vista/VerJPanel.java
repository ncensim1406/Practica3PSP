    private void actualizarInformacion(){
        Cliente actual = controlActual.obtenerClienteActual();
        nombreField.setText(actual.getNombre());
        puntosField.setText(actual.getPuntos());
        numeroField.setText(actual.getNumero()+"");
        fechaField.setText(actual.getFecha().toString());
    }

