    private void botonAtrasActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botonAtrasActionPerformed
        // TODO add your handling code here:
        if (!controlActual.esVacia()) {
            controlActual.retroceder();
            actualizarInformacion();
            if (controlActual.esPrimero()) {
                botonAtras.setVisible(false);
            }else if(!controlActual.esUltimo()){
                botonAdelante.setVisible(true);
            }
        }
    }//GEN-LAST:event_botonAtrasActionPerformed

    private void botonAdelanteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botonAdelanteActionPerformed
        if (!controlActual.esVacia()) {
            controlActual.avanzar();
            actualizarInformacion();
            if (controlActual.esUltimo()) {
                botonAdelante.setVisible(false);
            }else if(!controlActual.esPrimero()){
                botonAtras.setVisible(true);
            } 
        }
    }//GEN-LAST:event_botonAdelanteActionPerformed

